// Детерминированный keyword-фильтр кризисных сообщений. Первый и самый
// надёжный слой защиты — если сработал явный паттерн намерения суицида или
// самоповреждения, ответ пользователю формирует НЕ модель, а этот файл: LLM
// для этого сообщения не вызывается вообще. Системный промпт (systemPrompt.js)
// остаётся вторым слоем — он ловит более мягкие/неявные сигналы ("смысла нет",
// "всем было бы легче без меня"), которые этот фильтр намеренно не трогает,
// чтобы не давать ложных срабатываний на обычные обороты речи.

function normalize(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/\s+/g, ' ')
    .trim();
}

// ВАЖНО: \w в JS не matчит кириллицу (даже с флагом /u) — только [A-Za-z0-9_].
// Для окончаний слов используем \p{L}* (юникодная категория "буква").
// \s+ — чтобы не ломаться на лишних/двойных пробелах, (\s+\S+){0,2} между
// ключевыми словами — чтобы ловить раздельное написание и вставные слова
// ("не хочу больше жить", "уже давно не хочу жить" и т.п.)
const SUICIDE_PATTERNS = [
  /по\s?кон\p{L}*\s+с\s+соб\p{L}+/u,
  /по\s?кон\p{L}*(\s+\S+){0,2}\s+жизн\p{L}*/u,
  /(хочу|хотел[ао]?с?ь|желаю|мечтаю)(\s+\S+){0,2}\s+умереть/u,
  /не\s+хочу(\s+\S+){0,2}\s+жить/u,
  /жить\s+не\s+хочу/u,
  /уби(ть|ю|л[ао]?)\s+себя/u,
  /хочу\s+себя\s+уби\p{L}*/u,
  /суицид\p{L}*/u,
  /наложи(ть|л[ао]?)\s+на\s+себя\s+руки/u,
];

const SELF_HARM_PATTERNS = [
  /реж(у|ешь|ет|ут)\s+себя/u,
  /реж(у|ешь|ет|ут)\s+(руки|вены)/u,
  /порезал[ао]?\s+себя/u,
  /поранил[ао]?\s+себя/u,
  /причиня(ю|ешь|ет)\s+себе\s+боль/u,
  /самоповрежд\p{L}*/u,
  /наношу\s+себе\s+(повреждения|порезы|раны)/u,
  /(перереза\p{L}*|вскры\p{L}*)\s+вен\p{L}*/u,
];

const ALL_PATTERNS = [...SUICIDE_PATTERNS, ...SELF_HARM_PATTERNS];

function detectCrisis(text) {
  const normalized = normalize(text);
  if (!normalized) return false;
  return ALL_PATTERNS.some((re) => re.test(normalized));
}

// каждый ответ: номер горячей линии, "анонимно" + "бесплатно", без осуждения,
// без техник-заменителей самоповреждения. Формулировки написаны вручную, не
// моделью — выбираются случайно, чтобы не выглядело как copy-paste шаблон
const CRISIS_RESPONSES = [
  'Слушай, то что ты сейчас написал — это серьёзно, и я не хочу делать вид, что это можно решить парой фраз в переписке. Пожалуйста, позвони на горячую линию 8-800-2000-122 — это бесплатно, анонимно и круглосуточно по всей России, там есть живые люди, которые умеют помогать именно в такие моменты. Я рядом, но сейчас важнее поговорить с кем-то, кто может быть с тобой не только в чате.',
  'Я тебя услышал, и это не то, мимо чего можно пройти как будто ничего не сказано. Прямо сейчас, пожалуйста, набери 8-800-2000-122 — бесплатная и анонимная линия, работает круглосуточно, без всякого осуждения. Тебе правда не обязательно проходить через это в одиночку.',
  'То, что ты написал — важно, и я не буду делать вид, что не заметил. Есть люди, которые умеют помогать именно с этим: 8-800-2000-122, звонок бесплатный и анонимный, работают круглосуточно. Пожалуйста, попробуй позвонить — там выслушают без осуждения.',
  'Спасибо, что сказал мне это, а не промолчал. Но здесь мне правда важно, чтобы рядом с тобой был кто-то, кто может помочь по-настоящему: 8-800-2000-122, бесплатно, анонимно, круглосуточно. Пожалуйста, не откладывай звонок.',
];

function getCrisisResponse() {
  return CRISIS_RESPONSES[Math.floor(Math.random() * CRISIS_RESPONSES.length)];
}

module.exports = { detectCrisis, getCrisisResponse };
